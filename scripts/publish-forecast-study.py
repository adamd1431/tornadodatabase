"""Publish compact frozen coefficients, provenance and aggregate scores only."""
import argparse
import hashlib
import json
import gzip
from pathlib import Path
import importlib.util
spec=importlib.util.spec_from_file_location('forecast_study',Path(__file__).with_name('fit-forecast-study.py'))
fit=importlib.util.module_from_spec(spec)
spec.loader.exec_module(fit)

def main():
    parser=argparse.ArgumentParser();parser.add_argument('--data',required=True);args=parser.parse_args()
    root=Path(args.data);repo=Path(__file__).resolve().parent.parent;out=repo/'forecast-study';out.mkdir(exist_ok=True)
    frozen=(root/'selected-model-frozen.json').read_bytes();sha=hashlib.sha256(frozen).hexdigest()
    assert sha==(root/'model-freeze.sha256').read_text().strip()
    model=json.loads(frozen);model['frozenModelSha256']=sha
    (repo/'storm-forecast-calibration.js').write_text('// Generated by scripts/publish-forecast-study.py; freeze precedes held-out evaluation.\nexport default '+json.dumps(model,separators=(',',':'))+';\n',encoding='utf-8')
    for name in ['backtest-report.json','protocol-v2.json','case-audit.json','source-manifest.json']:
        (out/name).write_bytes((root/name).read_bytes())
    (out/'selected-model-frozen.json').write_bytes(frozen)
    study=fit.Study(root);prediction=study.base.copy()
    for region in ['nhc','jtwc']:
        for target,cols in fit.TARGETS.items():
            config=model['model'][region][target]
            if config['promotedFromValidation']:
                candidate=fit.predict(study,target,region,config);indices=fit.np.flatnonzero(study.region==region)
                prediction[fit.np.ix_(indices,cols)]=candidate[fit.np.ix_(indices,cols)]
    expected_all=study.unproject(prediction)
    with gzip.open(root/'runtime-predictions.json.gz','wt',encoding='utf-8') as file:
        json.dump([[float(v) if fit.np.isfinite(v) else None for v in row] for row in expected_all],file)
    examples=[]
    for region in ['nhc','jtwc']:
        for lead in fit.LEADS:
            indices=fit.np.flatnonzero((study.region==region)&(study.lead==lead)&fit.np.isin(study.split,['test2024global','test2025']))
            i=int(indices[0]);row=study.rows[i]
            expected=expected_all[i]
            examples.append({'id':row['id'],'at':row['at'],'initial':row['initial'],'trend':row['trend'],'lead':lead,'x':row['x'],'v1':row['v1'],'expected':[float(v) if fit.np.isfinite(v) else None for v in expected]})
    fixtures=repo/'tests'/'fixtures'/'forecast-study';fixtures.mkdir(exist_ok=True)
    (fixtures/'parity.json').write_text(json.dumps(examples,indent=2),encoding='utf-8')
    print('Published coefficients, provenance, aggregates and',len(examples),'cross-language parity cases. No raw guidance or full case dataset copied.')
if __name__=='__main__':main()
