const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const model=import('data:text/javascript;base64,'+fs.readFileSync(path.join(__dirname,'../wind-pressure-model.js')).toString('base64'));
const input={method:'ckk2025',mode:'wind',latitude:20,environmentMb:1010,radiusNmi:100,ckkRadiusMode:'quadrants',motionKnots:11};
const near=(actual,expected,tolerance=1e-7)=>assert.ok(Math.abs(actual-expected)<=tolerance,`${actual} != ${expected}`);

test('CKK 2025 matches the author’s Python reference with both R34 conventions',async()=>{
  const {pressureFromWind}=await model;
  // Generated by predict_Pmin_from_R34kt in the author's tcwindprofile code:
  // https://github.com/drchavas/tcwindprofile/blob/main/tcwindprofile/tc_pmin_estimatefromR34kt.py
  // Columns: point-max kt, reported mean nmi, latitude, motion kt, Pe mb,
  // reference pressure using mean × 0.85, reference using the radius directly.
  const references=[
    [100,100,20,11,1010,960.9712646829183,958.719201235197],
    [165,163.75,11.1,9,1006,898.1682136182117,895.4975096743701],
    [160,217.5,18.8,12,1008,889.121559873977,883.2650921649464],
    [140,150,-26.2,10.5,1011,913.9897596220568,908.7211262988378],
    [65,40,0,0,1005,984.1993770154321,984.1993770154321],
    [34,0,20,60,1010,1003.3966389058024,1003.3966389058024],
    [250,125,30,0,1010,759.910434794721,754.012579878321]
  ];
  for(const [wind,radiusNmi,latitude,motionKnots,environmentMb,quadrants,azimuthal] of references) {
    for(const [ckkRadiusMode,pressure] of [['quadrants',quadrants],['azimuthal',azimuthal]]) {
      const row=pressureFromWind(wind,{...input,radiusNmi,latitude,motionKnots,environmentMb,ckkRadiusMode});
      near(row.pressureMb,pressure,1e-10);
      near(row.meanWindMs,(wind-.55*motionKnots)*1852/3600);
      near(row.deficit,environmentMb-pressure);
    }
  }
});

test('CKK uses an explicit single radius correction, direct Pe, and hemisphere symmetry',async()=>{
  const {pressureFromWind,normalizeWindPressureOptions}=await model;
  const quadrants=pressureFromWind(100,input),azimuthal=pressureFromWind(100,{...input,radiusNmi:85,ckkRadiusMode:'azimuthal'});
  near(quadrants.pressureMb,azimuthal.pressureMb);near(quadrants.r34,85);near(quadrants.radiusMeters,157420);
  near(pressureFromWind(100,{...input,latitude:-20}).pressureMb,quadrants.pressureMb);
  near(pressureFromWind(100,{...input,environmentMb:1012}).pressureMb,quadrants.pressureMb+2);
  const options=normalizeWindPressureOptions({...input,brownFit:'bad',stationMb:''});
  assert.equal(options.radiusType,'r34');near(options.r34,85);
});

test('CKK reverse calculation inverts the same equation across the calculation range',async()=>{
  const {pressureFromWind,windsFromPressure}=await model;
  for(const ckkRadiusMode of ['quadrants','azimuthal'])for(const latitude of [0,18,30,-60])for(const radiusNmi of [0,100,300])for(const motionKnots of [0,11,60]) {
    const options={...input,ckkRadiusMode,latitude,radiusNmi,motionKnots};
    for(const wind of [25,34,65,100,165,250]) {
      if(wind<=.55*motionKnots || (wind<34 && radiusNmi>0))continue;
      let forward;
      try{forward=pressureFromWind(wind,options);}catch(error){assert.match(error.message,/below the environment/);continue;}
      const solutions=windsFromPressure(forward.pressureMb,options);
      assert.equal(solutions.length,1);near(solutions[0].windKnots,wind,1e-7);near(solutions[0].pressureMb,forward.pressureMb);
    }
  }
  assert.throws(()=>windsFromPressure(1009,{...input,radiusNmi:0,motionKnots:60}),error=>error.field==='pressureMb');
  assert.throws(()=>windsFromPressure(400,input),error=>error.field==='pressureMb');
});

test('CKK supports CI conversion and consistent canonical unit inputs',async()=>{
  const {calculateWindPressure,pressureFromWind,ciToWind,WIND_FACTORS,RADIUS_FACTORS}=await model;
  const ci=calculateWindPressure({...input,mode:'ci',ci:6});
  near(ci.solutions[0].windKnots,115);near(ci.solutions[0].pressureMb,pressureFromWind(ciToWind(6),input).pressureMb);
  for(const windUnit of ['kt','mph','kmh'])for(const radiusUnit of ['nmi','km']) {
    const wind=100*WIND_FACTORS[windUnit],radius=100*RADIUS_FACTORS[radiusUnit];
    const row=calculateWindPressure({...input,windKnots:wind/WIND_FACTORS[windUnit],radiusNmi:radius/RADIUS_FACTORS[radiusUnit]}).solutions[0];
    near(row.pressureMb,960.9712646829183);
  }
});

test('CKK validates relevant inputs and excludes nonpositive motion-corrected wind',async()=>{
  const {calculateWindPressure,pressureFromWind,normalizeWindPressureOptions}=await model;
  assert.throws(()=>normalizeWindPressureOptions({...input,radiusType:'roci'}),error=>error.field==='radiusType');
  for(const ckkRadiusMode of ['',undefined,'roci','constructor'])assert.throws(()=>normalizeWindPressureOptions({...input,ckkRadiusMode}),error=>error.field==='ckkRadiusMode');
  for(const radiusNmi of ['',null,true,-1,Infinity])assert.throws(()=>normalizeWindPressureOptions({...input,radiusNmi}),error=>error.field==='ckkRadiusNmi');
  for(const latitude of ['',null,61,-61,Infinity])assert.throws(()=>normalizeWindPressureOptions({...input,latitude}),error=>error.field==='latitude');
  for(const motionKnots of ['',null,-1,61,Infinity])assert.throws(()=>normalizeWindPressureOptions({...input,motionKnots}),error=>error.field==='motionKnots');
  for(const environmentMb of ['',null,799,1101,Infinity])assert.throws(()=>normalizeWindPressureOptions({...input,environmentMb}),error=>error.field==='environmentMb');
  for(const wind of ['',null,24,251,Infinity])assert.throws(()=>pressureFromWind(wind,input),error=>error.field==='windKnots');
  assert.throws(()=>pressureFromWind(25,input),error=>error.field==='ckkRadiusNmi');
  assert.throws(()=>pressureFromWind(25,{...input,radiusNmi:0,motionKnots:60}),error=>error.field==='windKnots');
  assert.throws(()=>pressureFromWind(100,{...input,radiusNmi:Number.MAX_VALUE}),error=>error.field==='ckkRadiusNmi');
  assert.throws(()=>calculateWindPressure({...input,mode:'ci',ci:9.1}),error=>error.field==='ci');
});

test('CKK charts remain finite and decreasing, including zero-radius high-motion cases',async()=>{
  const {windPressureCurve,pressureFromWind}=await model;
  for(const options of [input,{...input,radiusNmi:0,motionKnots:60},{...input,radiusNmi:0,motionKnots:0},{...input,latitude:0},{...input,radiusNmi:800,motionKnots:60}]) {
    const points=windPressureCurve(options);
    assert.ok(points.length>100);assert.equal(points.at(-1).windKnots,250);
    for(let index=0;index<points.length;index++) {
      const point=points[index];assert.ok(Number.isFinite(point.pressureMb));
      near(point.pressureMb,pressureFromWind(point.windKnots,options).pressureMb);
      if(index>0)assert.ok(point.pressureMb<points[index-1].pressureMb);
    }
  }
});
